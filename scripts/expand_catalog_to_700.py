async def fetch_videos(name: str, queries: list[str], search: RutubeApiSearch):
    hits = []
    for query in queries:
        hits.extend(await search.search(query, limit=3))
        await asyncio.sleep(0.12)
    hits = filter_relevant_video_hits(hits, exercise_name=name)
    return dedupe_videos(hits, limit_per_platform=2)


async def main() -> None:
    store = load_exercises_jsonl(EXERCISES_JSONL_PATH)
    before = len(store)
    target = 700
    need = max(0, target - before)
    print(f"catalog={before} target={target} need≈{need} candidates={len(NEW_EXERCISES)}")

    search = RutubeApiSearch()
    added = 0
    skipped = 0
    no_video: list[str] = []
    try:
        for item in NEW_EXERCISES:
            if len(store) >= target and added >= need:
                # still allow filling if under target from skips
                pass
            key = normalize_exercise_name(item["name"])
            if key in store:
                skipped += 1
                continue
            if len(store) >= target:
                break
            videos = await fetch_videos(item["name"], item["video_queries"], search)
            if not videos:
                no_video.append(item["name"])
            record = ExerciseJsonlRecord(
                name=item["name"],
                primary_muscles=item["primary_muscles"],
                secondary_muscles=item["secondary_muscles"],
                technique=item["technique"][:500],
                places=list(normalize_exercise_places(item["places"])),
                videos=videos,
            )
            upsert_exercise(store, record)
            added += 1
            print(f"+ ({len(store)}) {item['name']} videos={len(videos)}")
    finally:
        await search.aclose()

    write_exercises_jsonl(EXERCISES_JSONL_PATH, store.values())
    print(f"done total={len(store)} added={added} skipped_existing={skipped}")
    if no_video:
        print("no_video:", len(no_video), no_video[:10])


if __name__ == "__main__":
    asyncio.run(main())
